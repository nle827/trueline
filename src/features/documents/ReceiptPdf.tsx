import { Document, Page, StyleSheet, Text, View } from "@react-pdf/renderer";
import { formatSigned, formatUSD } from "@/domain/money";
import { COMPANY } from "@/domain/seed/company";
import { CATEGORIES } from "@/domain/trades";
import type { JobView } from "@/state/selectors";

const PINK = "#f3c6d0";
const CARBON = "#2c3d91";
const STAMP = "#c7303a";

const s = StyleSheet.create({
  page: { padding: 40, fontFamily: "Courier", fontSize: 10, color: CARBON, backgroundColor: PINK },
  title: { fontFamily: "Helvetica-Bold", fontSize: 28, color: "#2a2d31", letterSpacing: 2 },
  row: { flexDirection: "row", justifyContent: "space-between", marginBottom: 3 },
  section: { marginTop: 18 },
  label: { color: "#5f656d", fontSize: 8, marginBottom: 2 },
  heading: { fontFamily: "Helvetica-Bold", fontSize: 11, color: "#2a2d31", marginBottom: 4 },
  rule: { borderBottomWidth: 1, borderBottomColor: CARBON, marginVertical: 8, opacity: 0.4 },
  bold: { fontFamily: "Courier-Bold" },
  stamp: {
    position: "absolute",
    top: 40,
    right: 40,
    borderWidth: 3,
    borderColor: STAMP,
    color: STAMP,
    fontFamily: "Helvetica-Bold",
    fontSize: 26,
    paddingHorizontal: 10,
    paddingVertical: 2,
    transform: "rotate(-12deg)",
  },
});

const date = (iso?: string) => (iso ? new Date(iso).toLocaleDateString("en-US", { dateStyle: "medium" }) : "");
const LABEL = { material: "Materials", labor: "Labor", other: "Other" } as const;

export function ReceiptDocument({ view }: { view: JobView }) {
  const { job, customer, doc, totals } = view;
  return (
    <Document title={`${job.number} receipt`} author={COMPANY.name}>
      <Page size="LETTER" style={s.page}>
        <Text style={s.stamp}>PAID</Text>
        <Text style={s.title}>RECEIPT</Text>
        <Text>{COMPANY.name} · {COMPANY.address}</Text>
        <Text>{COMPANY.phone} · {COMPANY.email}</Text>

        <View style={[s.section, s.row]}>
          <View>
            <Text style={s.label}>RECEIVED FROM</Text>
            <Text style={s.bold}>{customer.name}</Text>
            <Text>{customer.address}</Text>
          </View>
          <View>
            <Text style={s.label}>REFERENCE</Text>
            <Text>Job {job.number}</Text>
            <Text>Invoice {doc.invoiceNumber}</Text>
            <Text>Issued {date(doc.issuedAt)}</Text>
          </View>
        </View>

        <View style={s.section}>
          <Text style={s.heading}>{job.title}</Text>
          {CATEGORIES.map((c) =>
            totals.byCategory[c].price > 0 ? (
              <View key={c} style={s.row}>
                <Text>{LABEL[c]}</Text>
                <Text>{formatUSD(totals.byCategory[c].price)}</Text>
              </View>
            ) : null,
          )}
          {view.changeOrders
            .filter((c) => c.status === "approved")
            .map((c) => (
              <View key={c.id} style={s.row}>
                <Text>Adjustment · {c.description}</Text>
                <Text>{formatSigned(c.amount)}</Text>
              </View>
            ))}
          {totals.discount > 0 && (
            <View style={s.row}>
              <Text>Discount</Text>
              <Text>-{formatUSD(totals.discount)}</Text>
            </View>
          )}
          <View style={s.row}>
            <Text>Sales tax (materials)</Text>
            <Text>{formatUSD(totals.tax)}</Text>
          </View>
          <View style={s.rule} />
          <View style={s.row}>
            <Text style={s.bold}>Total</Text>
            <Text style={s.bold}>{formatUSD(totals.total)}</Text>
          </View>
        </View>

        <View style={s.section}>
          <Text style={s.heading}>Payments</Text>
          {view.payments.map((p) => (
            <View key={p.id} style={s.row}>
              <Text>{date(p.receivedAt)} · {p.method === "ach" ? "bank transfer" : p.method}</Text>
              <Text>{formatUSD(p.amount)}</Text>
            </View>
          ))}
          <View style={s.rule} />
          <View style={s.row}>
            <Text style={s.bold}>Balance</Text>
            <Text style={s.bold}>{formatUSD(Math.max(0, view.balance))}</Text>
          </View>
        </View>

        <Text style={[s.section, { fontSize: 8, color: "#5f656d" }]}>
          Demo document generated by Trueline. {COMPANY.name} is a fictional company.
        </Text>
      </Page>
    </Document>
  );
}
